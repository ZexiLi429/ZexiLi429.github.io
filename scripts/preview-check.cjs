const { chromium } = require('C:/Users/Dell/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('fs')
const path = require('path')
const assert = require('node:assert/strict')

;(async () => {
  fs.mkdirSync('preview-artifacts', { recursive: true })
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist'] })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => document.querySelector('.studio-canvas canvas'))
  await page.waitForTimeout(8000)
  await page.waitForFunction(() => document.querySelector('[data-model-status="ready"]'))
  await page.screenshot({ path: 'preview-artifacts/01-home.png' })
  assert.equal(await page.locator('h1').innerText(), '你好呀，我是\n李泽曦')
  await page.evaluate(() => window.scrollTo({ top: innerHeight * .72, behavior: 'instant' }))
  await page.waitForTimeout(4000)
  await page.screenshot({ path: 'preview-artifacts/02-hello.png' })
  for (const id of ['about', 'projects', 'music', 'resume']) {
    await page.evaluate(id => window.scrollTo({ top: document.getElementById(id).getBoundingClientRect().top + scrollY, behavior: 'instant' }), id)
    await page.waitForTimeout(1800)
    await page.screenshot({ path: `preview-artifacts/03-${id}.png` })
    assert.equal(await page.locator(`.studio-nav a[href="#${id}"]`).getAttribute('aria-current'), 'location')
  }
  await page.locator('.studio-nav a[href="#projects"]').click()
  await page.waitForTimeout(2200)
  await page.locator('.project-list button').first().focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('dialog').open)
  await page.screenshot({ path: 'preview-artifacts/04-detail.png' })
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('dialog').evaluate(dialog => dialog.open), false)
  assert.equal(await page.locator('.project-list button').first().evaluate(button => button === document.activeElement), true)
  await page.locator('.studio-nav nav a[href="#home"]').click()
  await page.waitForTimeout(2400)
  assert.ok(await page.evaluate(() => scrollY < 5))
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 })
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' })
  await mobile.waitForTimeout(8000)
  await mobile.screenshot({ path: 'preview-artifacts/05-mobile-home.png' })
  await mobile.evaluate(() => window.scrollTo({ top: innerHeight * .72, behavior: 'instant' }))
  await mobile.waitForTimeout(1800)
  await mobile.screenshot({ path: 'preview-artifacts/05-mobile-hello.png' })
  for (const id of ['about', 'projects', 'music', 'resume']) {
    await mobile.evaluate(id => window.scrollTo({ top: document.getElementById(id).getBoundingClientRect().top + scrollY, behavior: 'instant' }), id)
    await mobile.waitForTimeout(2200)
    await mobile.screenshot({ path: `preview-artifacts/06-mobile-${id}.png` })
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  const reduced = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' })
  await reduced.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' })
  await reduced.waitForTimeout(6000)
  await reduced.locator('.hero-sticky nav a[href="#about"]').last().click()
  await reduced.waitForTimeout(1200)
  await reduced.screenshot({ path: 'preview-artifacts/07-reduced.png' })
  assert.equal(await reduced.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto')
  const fallback = await browser.newPage()
  await fallback.route('**/models/scholar-head.glb', route => route.abort())
  await fallback.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' })
  await fallback.evaluate(() => window.scrollTo({ top: document.getElementById('projects').getBoundingClientRect().top + scrollY, behavior: 'instant' }))
  await fallback.waitForTimeout(2500)
  assert.equal(await fallback.locator('.studio-fallback').count(), 1)
  await fallback.locator('.project-list button').first().click()
  assert.equal(await fallback.locator('dialog').evaluate(dialog => dialog.open), true)
  fs.writeFileSync('preview-artifacts/check-results.json', JSON.stringify({ passed: true, errors, screenshots: fs.readdirSync('preview-artifacts').filter(x => x.endsWith('.png')) }, null, 2))
  console.log(JSON.stringify({ passed: true, errors, output: path.resolve('preview-artifacts') }))
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
