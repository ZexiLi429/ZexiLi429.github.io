process.env.PLAYWRIGHT_BROWSERS_PATH = require('path').resolve('node_modules/.cache/playwright')
const { chromium } = require('C:/Users/Dell/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('fs')
const crypto = require('crypto')
const assert = require('node:assert/strict')
const digest = buffer => crypto.createHash('sha256').update(buffer).digest('hex')

;(async () => {
  fs.mkdirSync('preview-artifacts', { recursive: true })
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: 'preview-artifacts', size: { width: 1440, height: 900 } } })
  const page = await context.newPage(), errors = []
  const settled = () => page.waitForFunction(() => document.querySelector('.studio-canvas')?.dataset.cameraSettled === 'true')
  const cameraPose = () => page.locator('.studio-canvas').evaluate(element => JSON.parse(element.dataset.cameraPose))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => document.querySelector('[data-model-status="ready"]'))
  await page.evaluate(() => document.fonts.ready)
  for (const [name, fraction] of [['upper-left', .12], ['face-closeup', .38], ['desk-reveal', .8]]) {
    await page.evaluate(fraction => window.scrollTo({ top: innerHeight * fraction, behavior: 'instant' }), fraction)
    await page.waitForTimeout(1800)
    await settled()
    await page.screenshot({ path: `preview-artifacts/cinema-${name}.png` })
  }
  const stops = await page.evaluate(() => ['about', 'projects', 'music', 'resume'].map(id => document.getElementById(id).getBoundingClientRect().top + scrollY - innerHeight * .1))
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await page.waitForTimeout(1800)
  // Record the real continuous glide rather than only end frames.
  const glide = async (target, duration) => page.evaluate(async ({ target, duration }) => {
    const start = scrollY, at = performance.now()
    await new Promise(resolve => {
      const tick = time => { const t = Math.min(1, (time - at) / duration); const eased = t * t * (3 - 2 * t); window.scrollTo({ top: start + (target - start) * eased, behavior: 'instant' }); if (t < 1) requestAnimationFrame(tick); else resolve() }
      requestAnimationFrame(tick)
    })
  }, { target, duration })
  await glide(720, 6500)
  for (const stop of stops) { await glide(stop, 4300); await page.waitForTimeout(1600); await settled() }
  const lastFrame = await page.locator('.studio-canvas').screenshot()
  await page.waitForTimeout(1000)
  assert.equal(digest(await page.locator('.studio-canvas').screenshot()), digest(lastFrame), 'reading camera must hold still')
  await page.screenshot({ path: 'preview-artifacts/cinema-final-desk.png' })
  await glide(stops[2], 3500); await page.waitForTimeout(1500)
  await glide(stops[3], 3500); await page.waitForTimeout(1900); await settled()
  assert.equal(digest(await page.locator('.studio-canvas').screenshot()), digest(lastFrame), 'reverse scroll must return to same camera frame')
  await glide(stops[1], 3500); await page.waitForTimeout(1700); await settled()
  const beforeDetail = await cameraPose()
  await page.locator('.project-list button').first().click(); await page.waitForTimeout(2200); await settled()
  const duringDetail = await cameraPose()
  assert.notDeepEqual(beforeDetail, duringDetail, 'project click should reframe the workstation')
  await page.screenshot({ path: 'preview-artifacts/cinema-project-focus.png' })
  await page.keyboard.press('Escape'); await page.waitForTimeout(2200); await settled()
  assert.deepEqual(await cameraPose(), beforeDetail, 'closing detail should restore the camera')
  assert.equal(await page.locator('.project-list button').first().evaluate(button => button === document.activeElement), true)
  const video = page.video()
  await context.close()
  await video.saveAs('preview-artifacts/cinematic-tour.webm')
  assert.deepEqual(errors, [])
  fs.writeFileSync('preview-artifacts/cinematic-results.json', JSON.stringify({ passed: true, checks: ['opening shots', 'continuous glides', 'held reading frame', 'reverse scroll returns', 'project focus and restore'], errors }, null, 2))
  console.log('Cinematic checks passed. Video: preview-artifacts/cinematic-tour.webm')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
